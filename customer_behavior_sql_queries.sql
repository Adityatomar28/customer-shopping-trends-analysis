-- Q1. What is the total revenue generated by male vs. female customers?
SELECT 
    gender, 
    COUNT(customer_id) AS total_transactions,
    ROUND(SUM(purchase_amount), 2) AS total_revenue,
    ROUND(AVG(purchase_amount), 2) AS avg_purchase_amount
FROM customer
GROUP BY gender
ORDER BY total_revenue DESC;


-- Q2. Which customers used a discount but still spent more than the average purchase amount? 
SELECT 
    customer_id, 
    purchase_amount,
    discount_applied
FROM customer 
WHERE discount_applied = 'Yes' 
  AND purchase_amount >= (SELECT AVG(purchase_amount) FROM customer)
ORDER BY purchase_amount DESC;


-- Q3. Which are the top 5 products with the highest average review rating?
SELECT 
    item_purchased, 
    ROUND(AVG(CAST(review_rating AS NUMERIC)), 2) AS avg_rating,
    COUNT(customer_id) AS total_reviews
FROM customer
GROUP BY item_purchased
ORDER BY avg_rating DESC, total_reviews DESC
LIMIT 5;


-- Q4. Compare the average Purchase Amounts between Standard and Express Shipping. 
SELECT 
    shipping_type, 
    COUNT(customer_id) AS total_orders,
    ROUND(AVG(purchase_amount), 2) AS avg_purchase_amount,
    ROUND(SUM(purchase_amount), 2) AS total_revenue
FROM customer
WHERE shipping_type IN ('Standard', 'Express')
GROUP BY shipping_type;


-- Q5. Do subscribed customers spend more? Compare average spend and total revenue between subscribers and non-subscribers.
SELECT 
    subscription_status,
    COUNT(customer_id) AS total_customers,
    ROUND(AVG(purchase_amount), 2) AS avg_spend,
    ROUND(SUM(purchase_amount), 2) AS total_revenue
FROM customer
GROUP BY subscription_status
ORDER BY total_revenue DESC, avg_spend DESC;


-- Q6. Which 5 products have the highest percentage of purchases with discounts applied?
SELECT 
    item_purchased,
    COUNT(*) AS total_orders,
    ROUND(100.0 * SUM(CASE WHEN discount_applied = 'Yes' THEN 1 ELSE 0 END) / COUNT(*), 2) AS discount_rate_pct
FROM customer
GROUP BY item_purchased
ORDER BY discount_rate_pct DESC
LIMIT 5;


-- Q7. Segment customers into New, Returning, and Loyal based on their number of previous purchases.
WITH customer_segments AS (
    SELECT 
        customer_id, 
        previous_purchases,
        CASE 
            WHEN previous_purchases = 1 THEN 'New'
            WHEN previous_purchases BETWEEN 2 AND 10 THEN 'Returning'
            ELSE 'Loyal'
        END AS customer_segment
    FROM customer
)
SELECT 
    customer_segment,
    COUNT(*) AS number_of_customers,
    ROUND(100.0 * COUNT(*) / (SELECT COUNT(*) FROM customer), 2) AS percentage_of_total
FROM customer_segments 
GROUP BY customer_segment
ORDER BY number_of_customers DESC;


-- Q8. What are the top 3 most purchased products within each category? 
WITH ranked_items AS (
    SELECT 
        category,
        item_purchased,
        COUNT(customer_id) AS total_orders,
        ROW_NUMBER() OVER (PARTITION BY category ORDER BY COUNT(customer_id) DESC) AS item_rank
    FROM customer
    GROUP BY category, item_purchased
)
SELECT 
    category,
    item_rank,
    item_purchased, 
    total_orders
FROM ranked_items
WHERE item_rank <= 3
ORDER BY category, item_rank;


-- Q9. Are customers who are repeat buyers (more than 5 previous purchases) likely to subscribe?
SELECT 
    subscription_status,
    COUNT(customer_id) AS repeat_buyers_count,
    ROUND(100.0 * COUNT(customer_id) / SUM(COUNT(customer_id)) OVER(), 2) AS percentage
FROM customer
WHERE previous_purchases > 5
GROUP BY subscription_status;


-- Q10. What is the revenue contribution of each age group? 
SELECT 
    age_group,
    COUNT(customer_id) AS total_customers,
    ROUND(SUM(purchase_amount), 2) AS total_revenue,
    ROUND(AVG(purchase_amount), 2) AS avg_order_value
FROM customer
GROUP BY age_group
ORDER BY total_revenue DESC;


