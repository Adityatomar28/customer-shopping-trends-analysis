-- Q11. Advanced RFM (Recency, Frequency, Monetary) Customer Scoring
-- Scores customers on Frequency (previous purchases) & Monetary Value (spend amount) using NTILE.
WITH rfm_scores AS (
    SELECT 
        customer_id,
        previous_purchases,
        purchase_amount,
        NTILE(4) OVER (ORDER BY previous_purchases ASC) AS frequency_score,
        NTILE(4) OVER (ORDER BY purchase_amount ASC) AS monetary_score
    FROM customer
)
SELECT 
    customer_id,
    previous_purchases,
    purchase_amount,
    frequency_score,
    monetary_score,
    (frequency_score + monetary_score) AS total_rfm_score,
    CASE 
        WHEN (frequency_score + monetary_score) >= 7 THEN 'Champion / High Value'
        WHEN (frequency_score + monetary_score) BETWEEN 5 AND 6 THEN 'Loyal Customer'
        WHEN (frequency_score + monetary_score) BETWEEN 3 AND 4 THEN 'Potential Loyalist'
        ELSE 'At Risk / Low Engagement'
    END AS customer_tier
FROM rfm_scores
ORDER BY total_rfm_score DESC, purchase_amount DESC
LIMIT 20;


-- Q12. State-Wise Market Penetration & Revenue Ranking
-- Ranks geographic locations by revenue and cumulative revenue share.
WITH state_summary AS (
    SELECT 
        location,
        COUNT(customer_id) AS total_orders,
        SUM(purchase_amount) AS state_revenue
    FROM customer
    GROUP BY location
)
SELECT 
    location,
    total_orders,
    state_revenue,
    DENSE_RANK() OVER (ORDER BY state_revenue DESC) AS revenue_rank,
    ROUND(100.0 * state_revenue / SUM(state_revenue) OVER(), 2) AS revenue_share_pct
FROM state_summary
ORDER BY revenue_rank ASC
LIMIT 15;


-- Q13. Discount Sensitivity & Basket Size Analysis
-- Evaluates whether promo codes/discounts encourage higher order values across categories.
SELECT 
    category,
    discount_applied,
    COUNT(customer_id) AS transaction_count,
    ROUND(AVG(purchase_amount), 2) AS avg_purchase_val,
    ROUND(SUM(purchase_amount), 2) AS category_revenue
FROM customer
GROUP BY category, discount_applied
ORDER BY category, discount_applied DESC;


-- Q14. Payment Method Preferences Across Age Demographics
-- Cross-tabulates payment channel adoption by age group.
SELECT 
    age_group,
    SUM(CASE WHEN payment_method = 'Credit Card' THEN 1 ELSE 0 END) AS credit_card_count,
    SUM(CASE WHEN payment_method = 'PayPal' THEN 1 ELSE 0 END) AS paypal_count,
    SUM(CASE WHEN payment_method = 'Venmo' THEN 1 ELSE 0 END) AS venmo_count,
    SUM(CASE WHEN payment_method = 'Cash' THEN 1 ELSE 0 END) AS cash_count,
    SUM(CASE WHEN payment_method = 'Debit Card' THEN 1 ELSE 0 END) AS debit_card_count,
    COUNT(*) AS total_transactions
FROM customer
GROUP BY age_group
ORDER BY total_transactions DESC;


-- Q15. Estimated Customer Lifetime Value (CLV) & Retention Potential
-- Calculates a proxy CLV based on previous purchase velocity and average order value.
SELECT 
    subscription_status,
    ROUND(AVG(previous_purchases), 1) AS avg_historical_orders,
    ROUND(AVG(purchase_amount), 2) AS avg_order_value,
    ROUND(AVG(previous_purchases * purchase_amount), 2) AS estimated_clv_proxy
FROM customer
GROUP BY subscription_status;
